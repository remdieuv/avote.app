test("validation titre + question + options + quiz", () => {
  const empty = validateCreateEventForm({
    eventTitle: "",
    questions: [createBlankQuestion("q-1")],
  });
  assert.equal(empty.ok, false);
  assert.ok(empty.fieldErrors.eventTitle);
  assert.ok(empty.fieldErrors.questions["q-1"].question);
  assert.ok(empty.fieldErrors.questions["q-1"].options);
  assert.equal(empty.firstErrorQuestionId, "q-1");

  const quizBad = validateCreateEventForm({
    eventTitle: "Soirée",
    questions: [
      {
        ...createBlankQuestion("q-2"),
        question: "Capitale ?",
        type: "QUIZ",
        options: ["Paris", "Lyon"],
        quizCorrectOrder: 9,
      },
    ],
  });
  assert.equal(quizBad.ok, false);
  assert.ok(quizBad.fieldErrors.questions["q-2"].quizCorrectOrder);

  const ok = validateCreateEventForm({
    eventTitle: "Soirée",
    questions: [
      {
        ...createBlankQuestion("q-3"),
        question: "Qui ?",
        options: ["A", "B"],
      },
    ],
  });
  assert.equal(ok.ok, true);
  assert.equal(ok.formError, null);
});

test("brouillon localStorage save/load/clear", () => {
  const store = memoryStorage();
  const draft = {
    eventTitle: "Test",
    eventDescription: "Desc",
    questions: [
      {
        ...createBlankQuestion("q-1"),
        question: "Hello",
        options: ["Oui", "Non"],
      },
    ],
  };
  assert.equal(isCreateEventDraftMeaningful(draft), true);
  assert.equal(isCreateEventDraftMeaningful({
    eventTitle: "",
    eventDescription: "",
    questions: [createBlankQuestion("q-1")],
  }), false);

  saveCreateEventDraft(store, draft);
  assert.ok(store.getItem(CREATE_EVENT_DRAFT_KEY));
  const loaded = loadCreateEventDraft(store);
  assert.equal(loaded?.eventTitle, "Test");
  assert.equal(loaded?.questions[0].question, "Hello");

  clearCreateEventDraft(store);
  assert.equal(loadCreateEventDraft(store), null);

  assert.equal(parseCreateEventDraft("not-json"), null);
  assert.ok(serializeCreateEventDraft(draft).includes('"v":1'));
});

