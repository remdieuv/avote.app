test("Changement de type : texte auto concours vidé / remplacé", () => {
  const contest = applyQuestionType(createBlankQuestion("q-1"), "CONTEST_ENTRY");
  assert.equal(contest.question, CONTEST_DEFAULT_QUESTION);
  assert.equal(isAutoGeneratedQuestionText(contest), true);

  const toSingle = applyQuestionType(contest, "SINGLE_CHOICE");
  assert.equal(toSingle.question, "");
  assert.equal(toSingle.contestQuestionCustomized, false);

  const withPrize = applyQuestionType(
    { ...createBlankQuestion("q-2"), contestPrize: "un voyage" },
    "CONTEST_ENTRY",
  );
  assert.equal(withPrize.question, buildContestQuestion("un voyage"));
  const toLead = applyQuestionType(withPrize, "LEAD");
  assert.equal(toLead.question, "");
  assert.equal(toLead.type, "LEAD");
});

test("Changement de type : texte personnalisé conservé", () => {
  const custom = {
    ...createBlankQuestion("q-1"),
    type: "CONTEST_ENTRY",
    question: "Ma question concours perso ?",
    options: ["Oui", "Non"],
    contestQuestionCustomized: true,
  };
  assert.equal(isAutoGeneratedQuestionText(custom), false);

  const toQuiz = applyQuestionType(custom, "QUIZ");
  assert.equal(toQuiz.question, "Ma question concours perso ?");
  assert.equal(toQuiz.type, "QUIZ");

  const fromSingle = {
    ...createBlankQuestion("q-2"),
    question: "Déjà saisie avant concours",
    options: ["A", "B"],
  };
  const toContest = applyQuestionType(fromSingle, "CONTEST_ENTRY");
  assert.equal(toContest.question, "Déjà saisie avant concours");
  assert.equal(toContest.contestQuestionCustomized, true);

  const emptyToContest = applyQuestionType(
    createBlankQuestion("q-3"),
    "CONTEST_ENTRY",
  );
  assert.equal(emptyToContest.question, CONTEST_DEFAULT_QUESTION);
  assert.equal(emptyToContest.contestQuestionCustomized, false);
});

